// @brief       二元归一化
// @param       x 所需要转换的值
// @param       y 所需要转换的值
// @return      float
//------------------------------------------------------------------------------------------------------------------
float normalization(float x,float y,float base,int mode)
{
  float sqare_sum = 0;
  float answer = 0;
  sqare_sum = sqrt((x * x) + (y * y));
  switch(mode)
  {
    case(0):{answer =(sqare_sum<=base)?(x):((base/sqare_sum) * x);break;}
    case(1):{answer =(sqare_sum<=base)?(y):((base/sqare_sum) * y);break;}
  }
  return answer;
}
