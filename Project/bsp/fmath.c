// @brief       求数值的符号+/-
// @param       x 所需要转换的值
// @return      float
//------------------------------------------------------------------------------------------------------------------
float SIGN(float x)
{ 
  float answer;
  if(x==0)
  {
    answer = 0;
  }
  else if(x>0)
  {
    answer = 1;
  }
  else
  {
    answer = -1;
  }
  return answer;
}
